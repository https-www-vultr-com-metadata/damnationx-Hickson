const assert = require('node:assert/strict');
const wasm = require(process.argv[2]);
// One RGBA8 mip, using the same offset-relative table as D2R.
const bytes = new Uint8Array(48);
bytes.set(Buffer.from('<DE('));
const view = new DataView(bytes.buffer);
view.setUint16(4, 31, true);
bytes[6] = 2; bytes[7] = 1;
view.setUint32(8, 1, true); view.setUint32(12, 1, true);
view.setUint32(36, 4, true); view.setUint32(40, 4, true);
bytes.set([11, 22, 33, 44], 44);
const image = wasm.decode_texture(bytes, 0);
assert.equal(image.width, 1);
assert.equal(image.height, 1);
assert.deepEqual([...image.rgba], [11, 22, 33, 44]);
image.free();
assert.throws(() => wasm.decode_texture(new Uint8Array(), 0), /not a D2R texture/);
const spriteBytes = new Uint8Array(48);
spriteBytes.set(Buffer.from('SpA1'));
const s = new DataView(spriteBytes.buffer);
s.setUint16(4, 31, true); s.setUint16(6, 1, true);
s.setUint32(8, 2, true); s.setUint32(12, 1, true);
s.setUint32(20, 2, true); s.setUint32(32, 8, true); s.setUint32(36, 4, true);
spriteBytes.set([1, 2, 3, 4, 5, 6, 7, 8], 40);
const sprite = wasm.decode_sprite(spriteBytes, 0, 1);
assert.equal(sprite.width, 2);
assert.deepEqual([...sprite.rgba], [1, 2, 3, 4, 5, 6, 7, 8]);
assert.equal(JSON.parse(sprite.metadata).frames.length, 2);
sprite.free();
assert.throws(() => wasm.parse_granny(new Uint8Array()), /GRFL/);
console.log('Rust WASM adapter tests passed');
